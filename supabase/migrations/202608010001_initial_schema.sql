-- RLS cannot tell whether a SELECT included an exact slug predicate. A broad
-- "is_active" SELECT policy would therefore permit enumeration. This narrow
-- SECURITY DEFINER function is the sole public read surface and returns neither
-- the internal UUID nor created_by. The 128-bit slug remains the access secret.
create or replace function public.get_public_dedication(p_slug text)
returns table (
  slug text,
  recipient_name text,
  recipient_status text,
  giver_name text,
  message text,
  theme_key text,
  created_at timestamptz
)
language sql
stable
security definer
set search_path = pg_catalog
as $$
  select
    d.slug,
    d.recipient_name,
    d.recipient_status,
    d.giver_name,
    d.message,
    d.theme_key,
    d.created_at
  from public.dedications as d
  where p_slug ~ '^d_[a-f0-9]{32}$'
    and d.slug = p_slug
    and d.visibility = 'unlisted'
    and d.is_active
  limit 1;
$$;

comment on function public.get_public_dedication(text) is
  'Exact-slug public lookup. Deliberately exposes no listing operation and no internal UUID.';

revoke all on table public.dedications from public, anon, authenticated;
